#!/usr/bin/env node
// Builds skills/ from the skills of the Arcus Claude plugin (plugins/arcus).
// The Claude plugin is the source of truth; this script only adapts wording and paths for Cursor.
//   node scripts/sync-skills.mjs <path to plugins/arcus>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SKILLS = ['setup', 'author', 'run', 'push'];
// The references a skill reads, with the ones those read in turn.
const REFERENCES = {
  author: ['editing', 'elements', 'platforms', 'reading-the-app'],
  run: ['editing', 'elements', 'platforms', 'reading-the-app', 'running'],
};

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source || !fs.existsSync(path.join(source, 'skills'))) {
  console.error('usage: node scripts/sync-skills.mjs <path to plugins/arcus of arcus-claude-plugin>');
  process.exit(2);
}

// A phrase written with single spaces matches across a line break in the source.
const phrase = (text) => new RegExp(text.trim().split(/\s+/).map(escape).join('\\s+'), 'g');
function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Each rule must match at least once, so a change in the source cannot silently skip an adaptation.
const RULES = [
  [/\$\{CLAUDE_PLUGIN_ROOT\}\/references\//g, 'references/'],
  [/\/arcus:(setup|author|run|push|help)\b/g, '/arcus-$1'],
  [/`(setup|author|run|push)` skill/g, '`arcus-$1` skill'],
  [/\bRead tool\b/g, 'file read tool'],
  [
    phrase('in a terminal (in Claude Code, `! arcus auth login` runs it in this session):'),
    'in a terminal (in Cursor, open a terminal and run it there):',
  ],
  [
    phrase('The variable must already be set in the terminal that started Claude Code.'),
    'The variable must already be set in the shell that the Cursor terminal tool uses.',
  ],
  [phrase('and restart Claude Code, or to run'), 'and restart Cursor, or to run'],
  [
    phrase('Give the Bash tool a longer timeout than that.'),
    'Give the terminal tool a longer timeout than that if it lets you set one. If it stops the command earlier, ask the user to run it in their own terminal and paste the JSON.',
  ],
];

const LEFTOVERS = /Claude|CLAUDE_|\/arcus:|! arcus|Bash tool|Read tool/;

const SETUP_ADDENDUM = `
## In Cursor

Arcus for Cursor sends your session events to Arcus while you are signed in with **Arcus: Sign In** (Command Palette).
That is a separate sign-in from \`arcus auth login\`, which the \`arcus\` CLI uses. Setup checks only the CLI sign-in.
You do not read or change the extension sign-in. If the user wants their sessions captured and has not signed in to
the extension, tell them to run **Arcus: Sign In**.
`;

function mustHold(rulesSeen, all) {
  RULES.forEach(([pattern], i) => {
    if (!rulesSeen[i]) throw new Error(`Source no longer contains: ${pattern}. Update the rule in scripts/sync-skills.mjs.`);
  });
  if (all.length === 0) throw new Error('No skills were produced.');
}

const seen = RULES.map(() => false);
const produced = [];
const note = (name) =>
  `\n<!-- Generated by scripts/sync-skills.mjs from skills/${name} of arcus-claude-plugin. Change it there, not here. -->\n`;

function transform(text, label) {
  let out = text;
  RULES.forEach(([pattern, replacement], i) => {
    const probe = new RegExp(pattern.source, pattern.flags);
    if (probe.test(out)) seen[i] = true;
    out = out.replace(pattern, replacement);
  });
  const left = out.match(LEFTOVERS);
  if (left) throw new Error(`${label} still has a Claude-only phrase: "${left[0]}"`);
  return out;
}

fs.rmSync(path.join(root, 'skills'), { recursive: true, force: true });

for (const skill of SKILLS) {
  const dest = path.join(root, 'skills', `arcus-${skill}`);
  fs.mkdirSync(dest, { recursive: true });
  let text = fs.readFileSync(path.join(source, 'skills', skill, 'SKILL.md'), 'utf8');
  text = text.replace(/^name: .*$/m, `name: arcus-${skill}`);
  text = transform(text, `skills/${skill}/SKILL.md`);
  const end = text.indexOf('\n---', 4) + 4;
  text = text.slice(0, end) + note(skill) + text.slice(end);
  if (skill === 'setup') text = text.replace(/\s*$/, '\n') + SETUP_ADDENDUM;
  fs.writeFileSync(path.join(dest, 'SKILL.md'), text);
  produced.push(skill);

  if (REFERENCES[skill]) {
    fs.mkdirSync(path.join(dest, 'references'), { recursive: true });
    for (const ref of REFERENCES[skill]) {
      const body = transform(fs.readFileSync(path.join(source, 'references', `${ref}.md`), 'utf8'), `references/${ref}.md`);
      fs.writeFileSync(path.join(dest, 'references', `${ref}.md`), body);
    }
  }
}

mustHold(seen, produced);
console.log(`Wrote ${produced.length} skills to skills/ from ${source}`);
